/**
 * The app's only text composable. The game font draws its lowercase letters as decorative stretched shapes
 * (and `o` as a circle), so every string is shown in capitals. Use this instead of Material's `Text`.
 */
@Composable
fun GameText(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontSize: TextUnit = TextUnit.Unspecified,
    fontStyle: FontStyle? = null,
    fontWeight: FontWeight? = null,
    fontFamily: FontFamily? = null,
    letterSpacing: TextUnit = TextUnit.Unspecified,
    textDecoration: TextDecoration? = null,
    textAlign: TextAlign? = null,
    lineHeight: TextUnit = TextUnit.Unspecified,
    overflow: TextOverflow = TextOverflow.Clip,
    softWrap: Boolean = true,
    maxLines: Int = Int.MAX_VALUE,
    minLines: Int = 1,
    onTextLayout: ((TextLayoutResult) -> Unit)? = null,
    style: TextStyle = LocalTextStyle.current,
) {
    Text(
        text = text.uppercase(),
        modifier = modifier,
        color = color,
        fontSize = fontSize,
        fontStyle = fontStyle,
        fontWeight = fontWeight,
        fontFamily = fontFamily,
        letterSpacing = letterSpacing,
        textDecoration = textDecoration,
        textAlign = textAlign,
        lineHeight = lineHeight,
        overflow = overflow,
        softWrap = softWrap,
        maxLines = maxLines,
        minLines = minLines,
        onTextLayout = onTextLayout,
        style = style,
    )
}

/** Shows typed text in capitals (for the game font) while keeping what the player typed unchanged. */
object UppercaseTransformation : VisualTransformation {
    override fun filter(text: AnnotatedString): TransformedText {
        val upper = text.text.uppercase()
        // Uppercasing can change length for a few letters (for example ß becomes SS); then show the text as typed.
        if (upper.length != text.text.length) return TransformedText(text, OffsetMapping.Identity)
        return TransformedText(AnnotatedString(upper), OffsetMapping.Identity)
    }
}
